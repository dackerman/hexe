fn parseGlyph(comptime rows: []const u8) [glyph_h]u8 {
    var out: [glyph_h]u8 = @splat(0);
    var it = std.mem.tokenizeScalar(u8, rows, ' ');
    var r: usize = 0;
    while (it.next()) |row| : (r += 1) {
        if (row.len != glyph_w) @compileError("glyph row must be 5 wide: " ++ rows);
        for (row, 0..) |c, x| {
            if (c == '#') out[r] |= @as(u8, 1) << @intCast(glyph_w - 1 - x);
        }
    }
    if (r != glyph_h) @compileError("glyph must have 7 rows: " ++ rows);
    return out;
}

/// The font in GPU layout: glyph_count * 2 words.
pub const words: [glyph_count * 2]u32 = blk: {
    @setEvalBranchQuota(100_000);
    var bitmaps: [glyph_count][glyph_h]u8 = @splat(@splat(0));
    for (glyphs) |g| bitmaps[g[0] - first_char] = parseGlyph(g[1]);
    for ('a'..'z' + 1) |c| bitmaps[c - first_char] = bitmaps[c - 'a' + 'A' - first_char];
    var w: [glyph_count * 2]u32 = @splat(0);
    for (bitmaps, 0..) |rows, i| {
        for (rows, 0..) |row, r| w[i * 2 + r / 4] |= @as(u32, row) << @intCast((r % 4) * 8);
    }
    break :blk w;
};

pub fn pixel(ch: u8, x: u32, y: u32) bool {
    if (ch < first_char or ch >= first_char + glyph_count or x >= glyph_w or y >= glyph_h) return false;
    const word = words[@as(usize, ch - first_char) * 2 + y / 4];
    const row = (word >> @intCast((y % 4) * 8)) & 0xff;
    return (row >> @intCast(glyph_w - 1 - x)) & 1 != 0;
}

test "font glyphs" {
    // '1' has its stem in the middle column on every row but the first two.
    try std.testing.expect(pixel('1', 2, 3));
    try std.testing.expect(!pixel('1', 0, 3));
    // 'H' crossbar.
    for (0..5) |x| try std.testing.expect(pixel('H', @intCast(x), 3));
    // lowercase maps to uppercase
    try std.testing.expectEqual(pixel('A', 0, 6), pixel('a', 0, 6));
    // space is empty
    for (0..5) |x| for (0..7) |y| try std.testing.expect(!pixel(' ', @intCast(x), @intCast(y)));
}
