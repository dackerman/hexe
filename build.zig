const std = @import("std");

/// Every GLSL shader in the project, relative to `shaders/`. Each one is
/// compiled by glslc into SPIR-V and exposed by the generated `shaders`
/// module as `shaders.<name>` where name is the path with `/` and `.`
/// replaced by `_` (e.g. `sim/grid/movement.comp` -> `sim_grid_movement_comp`).
/// Adding a shader: add its path here.
const shader_sources = [_][]const u8{
    // ---- M0 / debug ----
    "debug/noise.comp",
    "test/cell_accessors.comp",
    // ---- grid (M1, M2) ----
    "sim/grid/commands.comp",
    "sim/grid/activity.comp",
    "sim/grid/movement.comp",
    // ---- world streaming (M4) ----
    "sim/stream/upload.comp",
    "sim/stream/dirty.comp",
    // ---- end world streaming ----
    // ---- air field (M5) ----
    "sim/coarsen.comp",
    "sim/air/init.comp",
    "sim/air/prep.comp",
    "sim/air/inject_count.comp",
    "sim/air/inject_apply.comp",
    "sim/air/compact.comp",
    "sim/air/lbm.comp",
    "sim/air/effects.comp",
    "sim/air/gas_advect.comp",
    "sim/air/overlay.comp",
    "sim/air/sample.comp",
    "sim/air/downsample.comp",
    // ---- end air field ----
    // ---- bodies (M7) ----
    "sim/bodies/raster.comp",
    "sim/bodies/points.comp",
    "sim/bodies/eject_fallback.comp",
    // ---- render ----
    "render/fullscreen.vert",
    "render/world.frag",
    "render/hud.frag",
};

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const gpu_tests = b.option(bool, "gpu-tests", "Also run the GPU determinism check as part of `zig build test`") orelse false;

    const vk_xml = b.path("vendor/vulkan-headers/registry/vk.xml");

    // ---- shaders: glslc -> SPIR-V -> generated `shaders` module ----
    const shaders_step = b.step("shaders", "Compile all shaders");
    const shader_files = b.addWriteFiles();
    var shader_zig: std.ArrayList(u8) = .empty;
    shader_zig.appendSlice(b.allocator, "// Generated by build.zig. SPIR-V blobs, 4-byte aligned.\n") catch @panic("OOM");
    for (shader_sources) |src| {
        const name = b.allocator.dupe(u8, src) catch @panic("OOM");
        for (name) |*c| {
            if (c.* == '/' or c.* == '.') c.* = '_';
        }
        const spv_name = b.fmt("{s}.spv", .{name});
        const glslc = b.addSystemCommand(&.{ "glslc", "-O", "--target-env=vulkan1.3", "-std=460", "-Werror" });
        glslc.setName(b.fmt("glslc {s}", .{src}));
        glslc.addPrefixedDirectoryArg("-I", b.path("shaders"));
        glslc.addArgs(&.{ "-MD", "-MF" });
        _ = glslc.addDepFileOutputArg(b.fmt("{s}.d", .{name}));
        glslc.addArg("-o");
        const spv = glslc.addOutputFileArg(spv_name);
        glslc.addFileArg(b.path(b.fmt("shaders/{s}", .{src})));
        _ = shader_files.addCopyFile(spv, spv_name);
        shaders_step.dependOn(&b.addInstallFile(spv, b.fmt("shaders/{s}", .{spv_name})).step);
        shader_zig.print(b.allocator, "pub const {s} align(4) = @embedFile(\"{s}\").*;\n", .{ name, spv_name }) catch @panic("OOM");
    }
    const shaders_zig = shader_files.add("shaders.zig", shader_zig.items);

    // ---- SDL3 via translate-c of the system headers ----
    const sdl_c = b.addTranslateC(.{
        .root_source_file = b.path("src/platform/sdl_c.h"),
        .target = target,
        .optimize = optimize,
    });

    // ================= shared CPU modules (data, world, bodies) =================
    // --- data ---
    // Material/scenario data layer (src/data), its tests, and `zig build docs`.
    const data_options = b.addOptions();
    data_options.addOption([]const u8, "materials_dir", "materials");
    data_options.addOption([]const u8, "scenarios_dir", "scenarios");
    const data_mod = b.createModule(.{
        .root_source_file = b.path("src/data/data.zig"),
        .target = target,
        .optimize = optimize,
    });
    data_mod.addOptions("build_options", data_options);
    // --- end data ---

    // --- world ---
    const world_mod = b.createModule(.{
        .root_source_file = b.path("src/world/world.zig"),
        .target = target,
        .optimize = optimize,
    });
    // --- end world ---

    // --- bodies ---
    // Box2D v3.2.0 (package dependency, built by its own build.zig: SIMD on,
    // SSE2 baseline with runtime AVX2 dispatch, -ffp-contract=off) and the CPU
    // rigid-body layer in src/sim/bodies.zig.
    // See docs/decisions/14-box2d-build-and-bindings.md.
    const box2d_dep = b.dependency("box2d", .{ .target = target, .optimize = optimize });
    const box2d_mod = box2d_dep.module("box2d");
    const bodies_mod = b.createModule(.{
        .root_source_file = b.path("src/sim/bodies.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{.{ .name = "box2d", .module = box2d_mod }},
    });
    // --- end bodies ---

    const shared_imports = [_]std.Build.Module.Import{
        .{ .name = "data", .module = data_mod },
        .{ .name = "world", .module = world_mod },
        .{ .name = "box2d", .module = box2d_mod },
        .{ .name = "bodies", .module = bodies_mod },
    };
    // The fixed-mode executables (verify: ReleaseSafe, bench: ReleaseFast)
    // link Box2D since M7; a Debug libbox2d carries UBSan calls they do not
    // bundle the runtime for, so they get Box2D built in their own mode.
    const verify_imports = sharedImportsFor(b, target, .ReleaseSafe, data_mod, world_mod);
    const bench_imports = sharedImportsFor(b, target, .ReleaseFast, data_mod, world_mod);

    const exe = addHexe(b, .{
        .name = "hexe",
        .target = target,
        .optimize = optimize,
        .vk_xml = vk_xml,
        .sdl_c = sdl_c,
        .shaders_zig = shaders_zig,
        .shared = &shared_imports,
    });
    b.installArtifact(exe.compile);

    const run_cmd = b.addRunArtifact(exe.compile);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();
    b.step("run", "Run hexe").dependOn(&run_cmd.step);

    // ---- unit tests (CPU only) ----
    const test_step = b.step("test", "Run all unit tests (CPU only; -Dgpu-tests adds the GPU determinism check)");
    const exe_tests = b.addTest(.{ .root_module = exe.module });
    test_step.dependOn(&b.addRunArtifact(exe_tests).step);

    // ---- data: tests and `zig build docs` ----
    const data_tests = b.addTest(.{ .root_module = data_mod });
    const run_data_tests = b.addRunArtifact(data_tests);
    run_data_tests.setCwd(b.path(".")); // tests read materials/ and scenarios/
    run_data_tests.has_side_effects = true; // rerun when data files change
    test_step.dependOn(&run_data_tests.step);

    const gendocs = b.addExecutable(.{
        .name = "gendocs",
        .root_module = b.createModule(.{
            .root_source_file = b.path("tools/gendocs.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "data", .module = data_mod }},
        }),
    });
    const run_gendocs = b.addRunArtifact(gendocs);
    run_gendocs.setCwd(b.path("."));
    run_gendocs.addArgs(&.{ "materials", "docs/materials.md" });
    b.step("docs", "Regenerate docs/materials.md from materials/").dependOn(&run_gendocs.step);

    // ---- world: tests and `zig build worldgen` ----
    const world_tests = b.addTest(.{ .root_module = world_mod });
    test_step.dependOn(&b.addRunArtifact(world_tests).step);

    const worldgen_exe = b.addExecutable(.{
        .name = "worldgen",
        .root_module = b.createModule(.{
            .root_source_file = b.path("tools/worldgen.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "world", .module = world_mod }},
        }),
    });
    const worldgen_run = b.addRunArtifact(worldgen_exe);
    worldgen_run.addPassthruArgs();
    b.step("worldgen", "Generate a procgen preview image (world)").dependOn(&worldgen_run.step);

    // ---- bodies: tests and `zig build bodies-demo` ----
    const bodies_tests = b.addTest(.{ .name = "bodies-test", .root_module = bodies_mod });
    test_step.dependOn(&b.addRunArtifact(bodies_tests).step);

    const demo_mod = b.createModule(.{
        .root_source_file = b.path("tools/bodies_demo.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{.{ .name = "bodies", .module = bodies_mod }},
    });
    const demo = b.addExecutable(.{ .name = "bodies-demo", .root_module = demo_mod });
    const demo_run = b.addRunArtifact(demo);
    demo_run.addPassthruArgs();
    b.step("bodies-demo", "Headless beam bend-and-snap demo (ASCII)").dependOn(&demo_run.step);

    // ---- GPU determinism: CPU reference vs GPU, bit-for-bit (ReleaseSafe) ----
    const verify_exe = addHexe(b, .{
        .name = "hexe-verify",
        .target = target,
        .optimize = .safe,
        .vk_xml = vk_xml,
        .sdl_c = sdl_c,
        .shaders_zig = shaders_zig,
        .shared = &verify_imports,
    });
    const verify_run = b.addRunArtifact(verify_exe.compile);
    verify_run.addArgs(&.{ "--headless", "--verify-determinism" });
    verify_run.addPassthruArgs();
    b.step("verify-determinism", "Run the seeded scenario on GPU and CPU reference and compare every cell").dependOn(&verify_run.step);
    if (gpu_tests) test_step.dependOn(&verify_run.step);

    // ---- world streaming: GPU sink round trip (M4) ----
    const stream_run = b.addRunArtifact(verify_exe.compile);
    stream_run.addArgs(&.{ "--world-selftest", "--validation" });
    stream_run.has_side_effects = true;
    b.step("stream-test", "GPU world streaming self-test: upload, dirty bits, download, save, reload").dependOn(&stream_run.step);
    // ---- end world streaming ----

    // ---- bench: always ReleaseFast ----
    const bench_exe = addHexe(b, .{
        .name = "hexe-bench",
        .target = target,
        .optimize = .fast,
        .vk_xml = vk_xml,
        .sdl_c = sdl_c,
        .shaders_zig = shaders_zig,
        .shared = &bench_imports,
    });
    const bench_run = b.addRunArtifact(bench_exe.compile);
    bench_run.addArgs(&.{ "--headless", "--bench" });
    bench_run.addPassthruArgs();
    bench_run.has_side_effects = true;
    b.step("bench", "Run fixed benchmark scenes headless (ReleaseFast) and print per-pass GPU ms").dependOn(&bench_run.step);

    // ---- air field scenarios (M5): sealed room, corridor blast ----
    const air_test_run = b.addRunArtifact(bench_exe.compile);
    air_test_run.addArgs(&.{ "--headless", "--air-test" });
    air_test_run.addPassthruArgs();
    air_test_run.has_side_effects = true;
    b.step("air-test", "Air field scenarios 3 and 4 (docs/04-fluids.md) headless on the GPU").dependOn(&air_test_run.step);
}

/// Shared imports with Box2D and the bodies layer built in `optimize`.
fn sharedImportsFor(b: *std.Build, target: std.Build.ResolvedTarget, optimize: std.builtin.OptimizeMode, data_mod: *std.Build.Module, world_mod: *std.Build.Module) [4]std.Build.Module.Import {
    const box2d_mod = b.dependency("box2d", .{ .target = target, .optimize = optimize }).module("box2d");
    const bodies_mod = b.createModule(.{
        .root_source_file = b.path("src/sim/bodies.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{.{ .name = "box2d", .module = box2d_mod }},
    });
    return .{
        .{ .name = "data", .module = data_mod },
        .{ .name = "world", .module = world_mod },
        .{ .name = "box2d", .module = box2d_mod },
        .{ .name = "bodies", .module = bodies_mod },
    };
}

const HexeOptions = struct {
    name: []const u8,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.Optimize,
    vk_xml: std.Build.LazyPath,
    sdl_c: *std.Build.Step.TranslateC,
    shaders_zig: std.Build.LazyPath,
    shared: []const std.Build.Module.Import,
};

const Hexe = struct {
    compile: *std.Build.Step.Compile,
    module: *std.Build.Module,
};

fn addHexe(b: *std.Build, o: HexeOptions) Hexe {
    const vulkan = b.dependency("vulkan", .{ .registry = o.vk_xml }).module("vulkan-zig");
    const sdl = b.createModule(.{
        .root_source_file = o.sdl_c.getOutput(),
        .target = o.target,
        .optimize = o.optimize,
        .link_libc = true,
    });
    sdl.linkSystemLibrary("SDL3", .{});
    const shaders = b.createModule(.{ .root_source_file = o.shaders_zig });
    const module = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = o.target,
        .optimize = o.optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "vulkan", .module = vulkan },
            .{ .name = "sdl", .module = sdl },
            .{ .name = "shaders", .module = shaders },
        },
    });
    // Raw GLSL sources the CPU mirrors are checked against (see src/sim/cell.zig tests).
    module.addAnonymousImport("common_glsl", .{ .root_source_file = b.path("shaders/common.glsl") });
    module.addAnonymousImport("bodies_glsl", .{ .root_source_file = b.path("shaders/sim/bodies/bodies.glsl") });
    for (o.shared) |imp| module.addImport(imp.name, imp.module);
    const compile = b.addExecutable(.{ .name = o.name, .root_module = module });
    return .{ .compile = compile, .module = module };
}
